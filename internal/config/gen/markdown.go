// docsPath resolves docs/settings.md from this source file's location, for the same
// reason outputPath does.
func docsPath() (string, error) {
	_, self, _, ok := runtime.Caller(0)
	if !ok {
		return "", fmt.Errorf("cannot locate generator source path")
	}
	root := filepath.Join(filepath.Dir(self), "..", "..", "..")
	return filepath.Join(root, "docs", "settings.md"), nil
}

const settingsDocHead = `<!-- Generated by ` + "`go generate ./internal/config`" + ` from the settings registry.
Do not edit by hand: a test fails whenever this file and the registry disagree. -->

# Settings reference

Every setting app-tail stores, written out from the same registry the agent, the CLI
and the dashboard read. If a setting exists, it is on this page, with the default it
starts at and when a change to it takes effect.

Most people never need this page: the dashboard shows the everyday settings on each
feature's own card and keeps the rest behind **Advanced settings**. It is here for scripting,
fleet setups and anyone who wants to see every knob at once.

## Changing a setting

| From | How |
|---|---|
| Dashboard | **Settings** in the side rail, or the settings on each feature's card. |
| CLI, one setting | ` + "`app-tail settings set <key> <value>`" + `, where the key is either name in the first two columns. |
| CLI, several at once | ` + "`app-tail settings set --udp-timeout=120 --show-tray=true`" + ` |
| Terminal menu | ` + "`app-tail settings menu`" + ` |
| Read one back | ` + "`app-tail settings get <key>`" + `, or ` + "`app-tail settings list`" + ` for all of them. |
| API | ` + "`PUT /api/settings`" + ` with a JSON body keyed by the setting's key. Every API call carries the token; see [the API reference](api.md#authentication). |

Lists are comma separated on the command line and JSON arrays over the API. Secrets are
write-only everywhere: the agent reports whether one is stored, never what it is.

**Takes effect** says what a change needs before it is fully in force:

| Value | Meaning |
|---|---|
| at once | The running agent picks it up immediately. |
| at once, while connected | Pushed to the running Tailscale connection. A change made while it is down is kept and applied when it next comes up. |
| after ` + "`app-tail restart`" + ` | Rebuilds the Tailscale connection inside the running agent. The dashboard and the CLI say when one is due. |
| after app-tail restarts | The whole program has to stop and start again. |
| next start | Read once when app-tail starts. |

Settings marked *Advanced* sit behind **Advanced settings** in the dashboard. A
setting that belongs to a feature only does anything while that feature's switch is on;
its description names the switch.
`

