// renderSettingsDoc renders docs/settings.md from the registry. It refuses a field it
// cannot describe, so a new kind or section fails generation instead of leaving a
// setting misdescribed or missing from the page.
func renderSettingsDoc(schema []config.FieldSchema) ([]byte, error) {
	modules := make(map[config.FeatureModule]config.ModuleInfo)
	for _, m := range config.FeatureModules() {
		modules[m.ID] = m
	}

	groups := config.GroupsFor(schema)
	placed := make(map[config.Group]bool, len(groups))
	for _, g := range groups {
		placed[g.ID] = true
	}
	for _, f := range schema {
		if !placed[f.Group] {
			return nil, fmt.Errorf("setting %s names a section the registry does not declare", f.Key)
		}
	}

	var b bytes.Buffer
	b.WriteString(settingsDocHead)

	b.WriteString("\n## Feature switches\n\n")
	b.WriteString("Each optional feature has one switch that turns the whole of it on or off.\n\n")
	b.WriteString("| Feature | Switch | CLI | What it does |\n|---|---|---|---|\n")
	for _, m := range config.FeatureModules() {
		cli := ""
		for _, f := range schema {
			if f.Key == m.SwitchKey && f.CLIName != "" {
				cli = "`--" + f.CLIName + "`"
			}
		}
		fmt.Fprintf(&b, "| %s | `%s` | %s | %s |\n", cell(m.Label), m.SwitchKey, cli, cell(m.Description))
	}

	for _, g := range groups {
		fmt.Fprintf(&b, "\n## %s\n\n%s\n\n", g.Label, strings.TrimSpace(g.Description))
		b.WriteString("| Key | CLI flag | Type | Default | Takes effect | Description |\n")
		b.WriteString("|---|---|---|---|---|---|\n")
		for _, f := range schema {
			if f.Group != g.ID {
				continue
			}
			row, err := settingRow(f, modules)
			if err != nil {
				return nil, err
			}
			b.WriteString(row)
		}
	}
	return b.Bytes(), nil
}

// settingRow is one table row describing f.
func settingRow(f config.FieldSchema, modules map[config.FeatureModule]config.ModuleInfo) (string, error) {
	kind, err := typeCell(f)
	if err != nil {
		return "", err
	}
	def, err := defaultCell(f)
	if err != nil {
		return "", err
	}
	effect, ok := restartWords[f.Restart]
	if !ok {
		return "", fmt.Errorf("setting %s has restart class %d, which the reference has no words for", f.Key, f.Restart)
	}
	flag := ""
	if f.CLIName != "" {
		flag = "`--" + f.CLIName + "`"
	}

	notes := []string{"**" + cell(f.Label) + "**<br>" + cell(f.Help)}
	if f.ModuleSwitch != config.ModuleCore {
		m, ok := modules[f.ModuleSwitch]
		if !ok {
			return "", fmt.Errorf("setting %s switches module %s, which the registry does not declare", f.Key, f.ModuleSwitch)
		}
		notes = append(notes, "Turns the whole "+cell(m.Label)+" feature on or off.")
	}
	if f.Module != config.ModuleCore {
		m, ok := modules[f.Module]
		if !ok {
			return "", fmt.Errorf("setting %s belongs to module %s, which the registry does not declare", f.Key, f.Module)
		}
		notes = append(notes, "Does something only while `"+m.SwitchKey+"` is on.")
	}
	switch {
	case f.Derived:
		notes = append(notes, "Read-only, worked out from other settings.")
	case f.ReadOnly || f.Write == config.WriteNone:
		notes = append(notes, "Read-only.")
	case f.Write == config.WriteAutostart:
		notes = append(notes, "Changes the operating system's login item rather than the config file.")
	}
	if f.Deprecated != "" {
		notes = append(notes, "Deprecated: "+cell(f.Deprecated))
	}
	if len(f.Pinnable) > 0 {
		names := make([]string, len(f.Pinnable))
		for i, p := range f.Pinnable {
			names[i] = "`" + p + "`"
		}
		notes = append(notes, "Overridden by "+strings.Join(names, " or ")+" when set.")
	}
	if f.Tier == config.TierAdvanced {
		notes = append(notes, "*Advanced.*")
	}

	return fmt.Sprintf("| `%s` | %s | %s | %s | %s | %s |\n",
		f.Key, flag, kind, def, effect, strings.Join(notes, " ")), nil
}

// typeCell is the Type column: the kind in words, with an enum's choices or an int's
// bounds when it has them.
func typeCell(f config.FieldSchema) (string, error) {
	words, ok := kindWords[f.Kind]
	if !ok {
		return "", fmt.Errorf("setting %s has kind %d, which the reference has no words for", f.Key, f.Kind)
	}
	if f.Kind == config.KindEnum && len(f.Options) > 0 {
		values := make([]string, len(f.Options))
		for i, o := range f.Options {
			values[i] = "`" + o.Value + "`"
		}
		return "one of " + strings.Join(values, ", "), nil
	}
	c := f.Constraint
	switch {
	case c.Min != nil && c.Max != nil:
		return fmt.Sprintf("%s, %d to %d", words, *c.Min, *c.Max), nil
	case c.Min != nil:
		return fmt.Sprintf("%s, at least %d", words, *c.Min), nil
	case c.Max != nil:
		return fmt.Sprintf("%s, at most %d", words, *c.Max), nil
	}
	return words, nil
}

// defaultCell is the Default column. A nil Default is the zero value of the kind.
func defaultCell(f config.FieldSchema) (string, error) {
	switch {
	case f.Secret || f.Kind.Secret():
		return "write-only", nil
	case f.ReadOnly || f.Derived || f.Write == config.WriteNone:
		return "", nil
	}
	switch v := f.Default.(type) {
	case nil:
		switch {
		case f.Kind == config.KindBool:
			return "off", nil
		case f.Kind == config.KindInt:
			return "0", nil
		case listKinds[f.Kind]:
			return "none", nil
		}
		return "not set", nil
	case bool:
		if v {
			return "on", nil
		}
		return "off", nil
	case int:
		return strconv.Itoa(v), nil
	case string:
		if v == "" {
			return "not set", nil
		}
		return "`" + cell(v) + "`", nil
	case []string:
		if len(v) == 0 {
			return "none", nil
		}
		return "`" + cell(strings.Join(v, ", ")) + "`", nil
	}
	return "", fmt.Errorf("setting %s has a default of type %T, which the reference has no words for", f.Key, f.Default)
}

// cell makes s safe inside one Markdown table cell: one line, no column breaks, and no
// angle brackets a renderer would take for HTML.
func cell(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	return strings.NewReplacer("|", `\|`, "<", "&lt;", ">", "&gt;").Replace(s)
}
