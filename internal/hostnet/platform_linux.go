package hostnet

import (
	"context"
	"os"
	"strings"
)

// Supported reports whether this platform has an interface mode at all.
func Supported() bool { return true }

// Privileged reports whether this process can create the interface itself.
//
// Root rather than a capability check: the interface needs CAP_NET_ADMIN, and a process
// that has it without being root is a deployment nobody using this app has. Answering
// false there costs a helper that would have worked; answering true where it is wrong
// costs a teardown of the working node followed by a failure, which is worse.
func Privileged() bool { return os.Geteuid() == 0 }

// DefaultInterfaceName is the interface a new node gets. Linux takes the name it is
// given, and a fixed one is what makes an interface left behind by an unclean exit
// identifiable in `ip link`.
func DefaultInterfaceName() string { return "app-tail0" }

// resolvesPerDomain reports whether installing a resolver here means naming the domains it
// answers for. Linux takes a resolver carrying no domains as the machine's own, which is
// what a tailnet without split DNS is asking for.
func resolvesPerDomain() bool { return false }

// DetectConflict names another program managing a tailnet on this machine.
//
// The interface app-tail opened plays no part here: what is looked at is the daemon's own
// socket, which app-tail never creates.
func DetectConflict(context.Context, string) string {
	for _, path := range []string{
		"/var/run/tailscale/tailscaled.sock",
		"/run/tailscale/tailscaled.sock",
	} {
		if info, err := os.Stat(path); err == nil && info.Mode()&os.ModeSocket != 0 {
			return "the official Tailscale client is running on this machine (" + path + "). " +
				"Two clients cannot share the interface, the routes or the resolver " +
				"configuration, so stop it before switching app-tail to the " +
				"network-interface mode."
		}
	}
	return ""
}

// DetectLeftovers lists what a previous run left on the machine.
//
// A tun interface is removed by the kernel with the last reference, so what can outlive
// the process is the routing policy rule tailscale's Linux router installs. It is named
// here rather than removed silently because it is also what an unclean exit looks like.
func DetectLeftovers() []string {
	body, err := os.ReadFile("/etc/resolv.conf")
	if err != nil || !strings.Contains(string(body), "# resolv.conf(5) file generated by tailscale") {
		// A file this process cannot read is one it cannot recognise either, and this list is
		// read to tell somebody what is still on their machine: an entry that stands for a
		// read that never happened would have them undo something nothing here saw.
		return []string{}
	}
	return []string{"/etc/resolv.conf is still the one tailscale wrote"}
}

// CleanUpLeftovers removes what a previous run left behind.
//
// Nothing is removed here. The Linux resolver path has several shapes -- a direct file,
// a systemd-resolved link, a resolvconf hand-off -- and the configurator restores
// whichever one it took over when it closes. Guessing at that from outside is how a
// working resolv.conf gets replaced with a broken one.
func CleanUpLeftovers(func(format string, args ...any)) {}

// UndoFor is what a user runs by hand to remove the given leftovers, when the app is gone
// and something is still installed. It takes the list rather than scanning for one, so the
// undo always matches the findings that were reported.
func UndoFor(leftovers []string) []string {
	if len(leftovers) == 0 {
		return nil
	}
	return []string{"sudo resolvconf -u   # or restore /etc/resolv.conf from your distribution's default"}
}

// DetectMissing names a component the interface mode needs that is not on this machine.
// The tun module is loaded on demand by the kernel, and a kernel built without it fails
// at the point the interface is created, with its own message.
func DetectMissing() string { return "" }
