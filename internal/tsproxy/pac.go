package tsproxy

import (
	"fmt"
	"net/netip"
	"strings"
)

// PACConfig is everything the auto-config script is derived from. Nothing in the
// rendered file is hardcoded: the tailnet's own name domain, its address ranges and the
// subnets it reaches all differ per tailnet, and a script that guessed any of them
// would send traffic the wrong way on somebody else's.
type PACConfig struct {
	// ProxyAddr is the host:port a browser should send matching traffic to. Empty
	// means the proxy is not listening, and the script sends everything direct.
	ProxyAddr string
	// MagicDNSSuffix is the tailnet's name domain, without dots, such as
	// "tail1a2b3c.ts.net". It is the only way a MagicDNS name can be matched: a
	// browser's own resolver cannot resolve one, so a rule that had to resolve the
	// name first would never fire.
	MagicDNSSuffix string
	// Ranges are the tailnet's own address ranges, for a client that dials a literal
	// tailnet IP rather than a name.
	Ranges []netip.Prefix
	// Routes are the subnets this node reaches through tailnet subnet routers. They
	// are the real reason a generated script beats a hand-written CGNAT rule.
	Routes []netip.Prefix
	// TunnelSuffixes are the name suffixes app-tail's own connections answer for, such
	// as "office.internal". Like a MagicDNS name they can only be matched on the name:
	// nothing outside this process resolves one, so a browser sending such a request
	// direct gets no answer at all.
	TunnelSuffixes []string
	// ExitNode reports whether an exit node is selected, in which case everything --
	// not just the tailnet -- belongs on the proxy.
	ExitNode bool
	// Reason explains an all-direct script, so a user reading the file finds out why
	// rather than concluding it is broken.
	Reason string
}

// PAC renders the proxy auto-config script.
//
// The result is deterministic for a given config: browsers re-fetch it, and a file
// whose bytes changed for no reason invalidates caches and makes a diff useless.
func PAC(cfg PACConfig) string {
	var b strings.Builder
	b.WriteString("// Generated by app-tail. Do not edit: it is rebuilt from the tailnet's\n")
	b.WriteString("// current state every time it is fetched.\n")

	if cfg.ProxyAddr == "" {
		reason := cfg.Reason
		if reason == "" {
			reason = "the app-tail proxy is not listening"
		}
		fmt.Fprintf(&b, "//\n// Everything is direct: %s.\n", reason)
		b.WriteString("function FindProxyForURL(url, host) { return \"DIRECT\"; }\n")
		return b.String()
	}

	proxy := fmt.Sprintf("SOCKS5 %s; PROXY %s", cfg.ProxyAddr, cfg.ProxyAddr)
	fallback := "DIRECT"
	if cfg.ExitNode {
		// With an exit node selected, public traffic is meant to leave through it. A
		// direct fallback would quietly bypass the exit node for everything the rules
		// above did not match, which is the opposite of what selecting one is for.
		fallback = proxy
		b.WriteString("//\n// An exit node is selected, so everything goes through the proxy.\n")
	}

	skipped := unmatchable(cfg.Ranges, cfg.Routes)
	if len(skipped) > 0 {
		// Silence here would read as coverage. isInNet is unreliable for IPv6 across
		// PAC engines, and there is no name to match a numeric subnet on.
		fmt.Fprintf(&b, "//\n// Not covered, because a PAC file cannot match an IPv6 subnet reliably: %s\n",
			strings.Join(skipped, ", "))
		b.WriteString("// Reach these through the proxy directly (SOCKS5) rather than through this file.\n")
	}

	b.WriteString("\nfunction FindProxyForURL(url, host) {\n")
	fmt.Fprintf(&b, "  var proxy = %q;\n", proxy)
	b.WriteString("  var literal = /^\\d+\\.\\d+\\.\\d+\\.\\d+$/.test(host);\n\n")

	if cfg.MagicDNSSuffix != "" {
		b.WriteString("  // A MagicDNS name. Matched on the name itself: the browser's own\n")
		b.WriteString("  // resolver cannot resolve one, so dnsResolve would never answer.\n")
		fmt.Fprintf(&b, "  if (shExpMatch(host, %q) || shExpMatch(host, %q)) return proxy;\n\n",
			cfg.MagicDNSSuffix, "*."+cfg.MagicDNSSuffix)
	}

	for _, suffix := range cfg.TunnelSuffixes {
		suffix = strings.ToLower(strings.Trim(strings.TrimSpace(suffix), "."))
		if suffix == "" {
			continue
		}
		fmt.Fprintf(&b, "  // Names ending in %s, which only the proxy reaches.\n", suffix)
		fmt.Fprintf(&b, "  if (shExpMatch(host, %q) || shExpMatch(host, %q)) return proxy;\n\n",
			suffix, "*."+suffix)
	}

	for _, p := range cfg.Ranges {
		writeRule(&b, p, "a tailnet address")
	}
	for _, p := range cfg.Routes {
		writeRule(&b, p, "a subnet this tailnet routes")
	}

	fmt.Fprintf(&b, "  return %q;\n}\n", fallback)
	return b.String()
}

// writeRule emits the match for one prefix. IPv4 goes through isInNet, guarded so it is
// only ever handed a literal address -- isInNet resolves a name otherwise, and the
// browser's resolver knows nothing about the tailnet. IPv6 is matched on the text of the
// address, because isInNet's IPv6 behaviour differs between PAC engines.
func writeRule(b *strings.Builder, p netip.Prefix, why string) {
	if p.Addr().Is4() {
		fmt.Fprintf(b, "  // %s (%s)\n", why, p)
		fmt.Fprintf(b, "  if (literal && isInNet(host, %q, %q)) return proxy;\n\n",
			p.Masked().Addr().String(), v4Netmask(p.Bits()))
		return
	}
	if glob, ok := v6Glob(p); ok {
		fmt.Fprintf(b, "  // %s (%s)\n", why, p)
		fmt.Fprintf(b, "  if (shExpMatch(host, %q)) return proxy;\n\n", glob)
	}
}

// v4Netmask renders a prefix length as the dotted mask isInNet expects.
func v4Netmask(bits int) string {
	mask := ^uint32(0)
	if bits < 32 {
		mask <<= uint(32 - bits)
	}
	if bits == 0 {
		mask = 0
	}
	return fmt.Sprintf("%d.%d.%d.%d", byte(mask>>24), byte(mask>>16), byte(mask>>8), byte(mask))
}

// v6Glob renders an IPv6 prefix as a textual wildcard, which is only exact when the
// prefix ends on a hextet boundary. Anything else would match addresses outside the
// prefix, so it is reported as uncovered instead.
func v6Glob(p netip.Prefix) (string, bool) {
	bits := p.Bits()
	if bits == 0 || bits%16 != 0 {
		return "", false
	}
	groups := p.Masked().Addr().StringExpanded()
	parts := strings.Split(groups, ":")
	keep := bits / 16
	if keep > len(parts) {
		return "", false
	}
	// Leading zeros are written out in the expanded form but not by a browser
	// reporting a host, so they are trimmed to the form an address is actually seen in.
	trimmed := make([]string, 0, keep)
	for _, part := range parts[:keep] {
		if t := strings.TrimLeft(part, "0"); t != "" {
			trimmed = append(trimmed, t)
			continue
		}
		trimmed = append(trimmed, "0")
	}
	return strings.Join(trimmed, ":") + ":*", true
}

// unmatchable lists the prefixes no rule could be written for, so the script can say so
// rather than leave the user to discover the gap by watching traffic go the wrong way.
// It covers every group writeRule is given, because a prefix writeRule emits nothing for
// is invisible in the output and would otherwise read as covered.
func unmatchable(groups ...[]netip.Prefix) []string {
	var out []string
	for _, group := range groups {
		for _, p := range group {
			if p.Addr().Is4() {
				continue
			}
			if _, ok := v6Glob(p); !ok {
				out = append(out, p.String())
			}
		}
	}
	return out
}
