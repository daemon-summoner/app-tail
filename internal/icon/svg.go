package icon

import (
	"bytes"
	"fmt"
	"image/color"
)

// SVG renders the application icon as scalable pixel art, which is what the dashboard
// serves as its favicon. A browser rasterises it at whatever size the tab strip, the
// bookmark bar or a pinned shortcut asks for, so the mark is emitted as vector runs
// with crisp edges rather than as one raster that would blur at every other size.
//
// The output is committed at ui/public/favicon.svg and regenerated with
// `go generate ./internal/icon`; gen's drift test fails the suite when the two differ.
func SVG() []byte {
	var b bytes.Buffer
	b.WriteString(svgHeader)
	fmt.Fprintf(&b, "  <rect width=\"%d\" height=\"%d\" rx=\"%d\" fill=\"%s\"/>\n",
		Grid, Grid, cornerRadius, hex(backdrop))

	// Bubbles first, so the mark sits over them exactly as it does in the raster.
	for _, bub := range bubbles {
		fmt.Fprintf(&b, "  <rect x=\"%d\" y=\"%d\" width=\"%d\" height=\"%d\" fill=\"%s\"/>\n",
			bub.x, bub.y, bub.size, bub.size, hex(bubble))
	}

	// One rect per run of same-coloured cells: a rect per pixel would be correct and
	// four times the size, and browsers seam adjacent fills at fractional zoom.
	for y, row := range squid {
		for x := 0; x < Grid; {
			c := marks[row[x]]
			if c.A == 0 {
				x++
				continue
			}
			w := 1
			for x+w < Grid && marks[row[x+w]] == c {
				w++
			}
			fmt.Fprintf(&b, "  <rect x=\"%d\" y=\"%d\" width=\"%d\" height=\"1\" fill=\"%s\"/>\n", x, y, w, hex(c))
			x += w
		}
	}

	b.WriteString("</svg>\n")
	return b.Bytes()
}

const svgHeader = `<!-- Code generated by internal/icon/gen. DO NOT EDIT.
     Regenerate with: go generate ./internal/icon
     Source of truth: internal/icon/icon.go (the pixel map). -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" shape-rendering="crispEdges">
`

// hex renders a colour as the #rrggbb form SVG takes. Every colour in the palette is
// opaque, so alpha never needs carrying.
func hex(c color.NRGBA) string {
	return fmt.Sprintf("#%02x%02x%02x", c.R, c.G, c.B)
}
