import { useState, type ReactNode } from 'react'
import type { Direction, Forward, Protocol } from '../api'
import { CheckIcon, CopyIcon } from './shell/icons'

export function CopyButton({ text }: { text: string }) {
  const [copied, setCopied] = useState(false)
  const copy = async () => {
    try {
      await navigator.clipboard.writeText(text)
      setCopied(true)
      window.setTimeout(() => setCopied(false), 1500)
    } catch {
      /* clipboard access can be denied; the text stays selectable regardless */
    }
  }
  return (
    <button type="button" className="btn ghost small copy" onClick={() => void copy()}>
      {copied ? <CheckIcon /> : <CopyIcon />}
      {copied ? 'Copied' : 'Copy'}
    </button>
  )
}

/** CodeBlock is a command or config the user is meant to run somewhere else, with the
 *  copy affordance attached. Everything shown in one is generated by the agent, so
 *  what is copied is what was tested. */
export function CodeBlock({ text }: { text: string }) {
  return (
    <div className="snippet">
      <CopyButton text={text} />
      <pre>{text}</pre>
    </div>
  )
}

/** Scrim is the dimmed backdrop every dialog and drawer sits on, and the one place
 *  the dismiss rule lives. */
export function Scrim({ onClose, children }: { onClose: () => void; children: ReactNode }) {
  return (
    // Only a click that lands on the backdrop itself closes. Comparing the target to
    // the backdrop keeps clicks inside the dialog from closing it without the dialog
    // needing a handler of its own, and a drag that ends on the backdrop no longer
    // counts as a click on it.
    <div className="scrim" role="presentation" onClick={(e) => e.target === e.currentTarget && onClose()}>
      {children}
    </div>
  )
}

export function ProtocolBadge({ protocol }: { protocol: Protocol }) {
  // "both" is spelled out as the two transports it carries, which is clearer than
  // the bare word and matches the label the agent renders in its endpoint string.
  const label = protocol === 'both' ? 'tcp + udp' : protocol
  return <span className={`badge ${protocol}`}>{label}</span>
}

export function DirectionBadge({ direction }: { direction: Direction }) {
  const toTailnet = direction === 'to_tailnet'
  return (
    <span
      className={`badge ${direction}`}
      title={
        toTailnet
          ? 'Exposes a local service to your whole tailnet, subject to your ACLs'
          : 'Reaches a tailnet service from a local port on this machine'
      }
    >
      {toTailnet ? 'to tailnet' : 'to local'}
    </span>
  )
}

/** StatusDot pairs the colour with a word, so state is never conveyed by hue alone. */
export function StatusDot({ forward }: { forward: Forward }) {
  const { tone, label } = describeState(forward)
  return (
    <span className={`status ${tone}`} title={forward.error ?? undefined}>
      <span className="dot" aria-hidden="true" />
      {label}
    </span>
  )
}

function describeState(forward: Forward): { tone: string; label: string } {
  if (!forward.enabled) return { tone: 'off', label: 'disabled' }
  switch (forward.state) {
    case 'running':
      return { tone: 'running', label: 'running' }
    case 'error':
      return { tone: 'error', label: 'error' }
    default:
      return { tone: 'pending', label: 'waiting' }
  }
}

export function Toggle({
  checked,
  onChange,
  label,
  disabled,
}: {
  checked: boolean
  onChange: (next: boolean) => void
  label: string
  disabled?: boolean
}) {
  return (
    <span className="toggle">
      <input
        type="checkbox"
        checked={checked}
        disabled={disabled ?? false}
        aria-label={label}
        onChange={(e) => onChange(e.target.checked)}
      />
      <span className="track" />
      <span className="knob" />
    </span>
  )
}

export function Notice({
  tone = 'info',
  children,
}: {
  tone?: 'info' | 'warn' | 'error'
  children: ReactNode
}) {
  return <div className={`notice ${tone}`}>{children}</div>
}

const BYTE_UNITS = ['KB', 'MB', 'GB', 'TB', 'PB'] as const

/** formatBytes keeps counters readable at a glance during live polling. */
export function formatBytes(n: number): string {
  if (n < 1024) return `${n} B`
  let value = n / 1024
  let unit = 0
  while (value >= 1024 && unit < BYTE_UNITS.length - 1) {
    value /= 1024
    unit += 1
  }
  const suffix = BYTE_UNITS[unit] ?? 'PB'
  return `${value < 10 ? value.toFixed(1) : Math.round(value)} ${suffix}`
}

/** formatRate is a byte figure per second. It reuses formatBytes so a rate and a total
 *  never disagree about what a megabyte is, and rounds to zero below one byte a second:
 *  a machine carrying nothing should read as carrying nothing, not as 0.4 B/s. */
export function formatRate(bytesPerSecond: number): string {
  if (!Number.isFinite(bytesPerSecond) || bytesPerSecond < 1) return '0 B/s'
  return `${formatBytes(Math.round(bytesPerSecond))}/s`
}

/** Route puts this machine's side on the left in both directions and points the
 *  arrow the way traffic travels, so the blast radius of a to_tailnet forward reads
 *  at a glance instead of having to be decoded from the badge. */
export function Route({ forward }: { forward: Forward }) {
  const bound = `${forward.bindAddr || '127.0.0.1'}:${forward.listenPort}`
  // The agent reports the address it actually bound, which can differ from the
  // configured one when a port was auto-suggested; expose it on hover.
  const listeningTitle = forward.listening ? `listening on ${forward.listening}` : undefined

  if (forward.direction === 'to_local') {
    return (
      <span className="route">
        <span className="local" title={listeningTitle}>
          {bound}
        </span>
        <span className="arrow" aria-hidden="true">
          &rarr;
        </span>
        <span className="remote">{forward.target}</span>
        <span className="sr-only">reaches the tailnet service at {forward.target}</span>
      </span>
    )
  }
  return (
    <span className="route">
      <span className="local">{forward.target}</span>
      <span className="arrow" aria-hidden="true">
        &larr;
      </span>
      <span className="remote" title={listeningTitle}>
        tailnet:{forward.listenPort}
      </span>
      <span className="sr-only">
        exposed to the tailnet on port {forward.listenPort}
      </span>
    </span>
  )
}
